-- Oracle / MSKBSTEST: tablo varlığı ve zorunlu Code/Name/boolean alanları.
WITH required AS (
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'CODE' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'NAME' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'ISACTIVE' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'FORCESCOMMANDREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'RANKREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'MILITARYCLASSREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'MILITARYUNITREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'SENDERCHAIRREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'MILITARYOFFICEREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'REGISTRYNUMBERREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'MILITARYSCHOOLREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'LASTNOMINATIONDATEREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'HEIGHTWEIGHTREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'NTHADMISSIONREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'DISPATCHDOCUMENTDATEREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'DISPATCHDOCUMENTNOREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCADMISSIONTYPEDEF' AS table_name, 'PERTEMAPPROVALREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'CODE' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'NAME' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'ISACTIVE' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'TIMEINFORMATIONREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'ADDITIONALDESCRIPTIONREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'NEGATIVEDECISION' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'APPROVALREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'PERTEMAPPROVALREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'HCDECISIONDEF' AS table_name, 'DIAGNOSISREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'REASONFOREXAMINATIONDEF' AS table_name, 'CODE' AS column_name FROM dual
 UNION ALL
 SELECT 'REASONFOREXAMINATIONDEF' AS table_name, 'DESCRIPTION' AS column_name FROM dual
 UNION ALL
 SELECT 'REASONFOREXAMINATIONDEF' AS table_name, 'ISACTIVE' AS column_name FROM dual
 UNION ALL
 SELECT 'REASONFOREXAMINATIONDEF' AS table_name, 'DISPATCHREQUIRED' AS column_name FROM dual
 UNION ALL
 SELECT 'REASONFOREXAMINATIONDEF' AS table_name, 'CLASSIFICATIONEXAMINATION' AS column_name FROM dual
 UNION ALL
 SELECT 'REASONFOREXAMINATIONDEF' AS table_name, 'OBJECTIONABLE' AS column_name FROM dual
)
SELECT r.table_name,r.column_name,
       CASE WHEN c.column_name IS NULL THEN 'MISSING' ELSE c.data_type END AS source_data_type
FROM required r
LEFT JOIN all_tab_columns c ON c.owner='MSKBSTEST'
 AND c.table_name=r.table_name AND c.column_name=r.column_name
ORDER BY r.table_name,r.column_name;

-- Not: ISACTIVE kaynağında boşsa true seçilir, ancak zorunlu flag alanları
-- NULL/bozuksa Oracle 'INVALID_FLAG' döndürür ve PG aktarım reddeder.
